/*
 * Generates one self-contained Baidu TTS MP3 for every guide script, plus the
 * sentence offsets used by the mini-program player. Run with:
 *   node scripts/generate-baidu-audio.js
 */
const fs = require("fs");
const path = require("path");
const https = require("https");
const { SCRIPTS } = require("../data/scripts");

const BUILD_DIR = path.join(__dirname, "..", "audio-build");
const AUDIO_DIR = path.join(BUILD_DIR, "audio");
const MANIFEST_PATH = path.join(BUILD_DIR, "audio-manifest.js");
const CONCURRENCY = 3;
const RETRIES = 3;

function requestTts(text, attempt = 1) {
  const url =
    "https://fanyi.baidu.com/gettts?lan=en&spd=5&source=web&text=" +
    encodeURIComponent(text);
  return new Promise((resolve, reject) => {
    const request = https.get(url, { headers: { "User-Agent": "Mozilla/5.0" } }, (response) => {
      const chunks = [];
      response.on("data", (chunk) => chunks.push(chunk));
      response.on("end", () => {
        const audio = Buffer.concat(chunks);
        if (response.statusCode === 200 && audio.length > 100 && audio[0] === 0xff) {
          resolve(audio);
        } else {
          reject(new Error("Baidu TTS returned HTTP " + response.statusCode));
        }
      });
    });
    request.setTimeout(30000, () => request.destroy(new Error("Baidu TTS timed out")));
    request.on("error", (error) => {
      if (attempt < RETRIES) {
        setTimeout(() => requestTts(text, attempt + 1).then(resolve, reject), attempt * 800);
      } else {
        reject(error);
      }
    });
  });
}

// Baidu's endpoint returns MPEG-2 Layer III frames (576 samples per frame).
// Counting frames avoids depending on a local audio encoder for timing data.
function mp3Duration(buffer) {
  let offset = 0;
  let seconds = 0;
  const bitrateMpeg2Layer3 = [0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160];
  const sampleRatesMpeg2 = [22050, 24000, 16000];
  while (offset + 4 <= buffer.length) {
    if (buffer[offset] !== 0xff || (buffer[offset + 1] & 0xe0) !== 0xe0) {
      offset += 1;
      continue;
    }
    const version = (buffer[offset + 1] >> 3) & 3;
    const layer = (buffer[offset + 1] >> 1) & 3;
    const bitrateIndex = (buffer[offset + 2] >> 4) & 15;
    const sampleRateIndex = (buffer[offset + 2] >> 2) & 3;
    const padding = (buffer[offset + 2] >> 1) & 1;
    if (version !== 2 || layer !== 1 || !bitrateIndex || sampleRateIndex === 3) {
      offset += 1;
      continue;
    }
    const bitrate = bitrateMpeg2Layer3[bitrateIndex] * 1000;
    const sampleRate = sampleRatesMpeg2[sampleRateIndex];
    const frameLength = Math.floor((72 * bitrate) / sampleRate) + padding;
    if (frameLength < 4 || offset + frameLength > buffer.length) break;
    seconds += 576 / sampleRate;
    offset += frameLength;
  }
  return seconds;
}

async function mapLimit(items, worker) {
  let cursor = 0;
  const runners = Array.from({ length: Math.min(CONCURRENCY, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor++;
      await worker(items[index], index);
    }
  });
  await Promise.all(runners);
}

async function generateScript(script) {
  const output = [];
  const timings = new Array(script.sentences.length);
  let completed = 0;
  console.log("Generating " + script.id + " (" + script.sentences.length + " sentences)…");
  await mapLimit(script.sentences, async (sentence, index) => {
    const audio = await requestTts(sentence);
    output[index] = audio;
    completed += 1;
    if (completed === script.sentences.length || completed % 25 === 0) {
      console.log("  " + completed + "/" + script.sentences.length);
    }
  });

  let position = 0;
  output.forEach((audio, index) => {
    const duration = mp3Duration(audio);
    timings[index] = [Number(position.toFixed(3)), Number((position + duration).toFixed(3))];
    position += duration;
  });
  const filename = script.id + ".mp3";
  fs.writeFileSync(path.join(AUDIO_DIR, filename), Buffer.concat(output));
  return { file: "/audio/" + filename, timings };
}

async function main() {
  fs.mkdirSync(AUDIO_DIR, { recursive: true });
  const manifest = {};
  for (const script of SCRIPTS) manifest[script.id] = await generateScript(script);
  fs.writeFileSync(
    MANIFEST_PATH,
    "// Generated by scripts/generate-baidu-audio.js.\nmodule.exports = " + JSON.stringify(manifest) + ";\n"
  );
  console.log("Created " + SCRIPTS.length + " MP3 files in audio-build/. Run split-audio-packages.js next.");
}

main().catch((error) => {
  console.error("Audio generation failed:", error.message);
  process.exitCode = 1;
});
