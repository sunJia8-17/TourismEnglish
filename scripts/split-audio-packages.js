/* Splits the generated local audio into six <= 2 MB mini-program subpackages. */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const template = path.join(root, "scripts", "guide-pages-template");
const sourceAudio = path.join(root, "audio-build", "audio");
const sourceManifest = require(path.join(root, "audio-build", "audio-manifest"));

for (const [id, entry] of Object.entries(sourceManifest)) {
  const packageRoot = path.join(root, "guides", id);
  fs.rmSync(packageRoot, { recursive: true, force: true });
  const pageRoot = path.join(packageRoot, "pages");
  fs.mkdirSync(pageRoot, { recursive: true });
  fs.mkdirSync(path.join(packageRoot, "audio"), { recursive: true });
  fs.cpSync(template, pageRoot, { recursive: true });

  for (const page of ["practice/practice.js", "result/result.js"]) {
    const file = path.join(pageRoot, page);
    fs.writeFileSync(
      file,
      fs.readFileSync(file, "utf8").replace(
        /"\.\.\/\.\.\/\.\.\/(data|utils)\//g,
        '"../../../../$1/'
      )
    );
  }

  const filename = path.basename(entry.file);
  fs.renameSync(path.join(sourceAudio, filename), path.join(packageRoot, "audio", filename));
  const packageEntry = {
    [id]: { file: "/guides/" + id + "/audio/" + filename, timings: entry.timings }
  };
  fs.writeFileSync(
    path.join(packageRoot, "audio-manifest.js"),
    "// Generated by scripts/generate-baidu-audio.js.\nmodule.exports = " + JSON.stringify(packageEntry) + ";\n"
  );
}

fs.rmSync(path.join(root, "audio-build"), { recursive: true, force: true });
console.log("Created six guide subpackages.");
